/**
 * Safely resolves any creator ID or name to a full CreatorInfo.
 * If not in predefined list, dynamically creates a community creator object with verified: false.
 */
export function resolveCreator(idOrName: string): CreatorInfo {
  if (!idOrName || typeof idOrName !== 'string') {
    return {
      id: 'community-creator',
      name: 'Community Creator',
      avatarUrl: 'https://mc-heads.net/avatar/Steve/128',
      verified: false,
      totalProducts: 1,
    };
  }

  const cleaned = idOrName.trim();
  const lower = cleaned.toLowerCase();

  const found = CREATORS.find(
    (c) => c.id.toLowerCase() === lower || c.name.toLowerCase() === lower
  );

  if (found) {
    return found;
  }

  const generatedId = lower.replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'author';
  return {
    id: generatedId,
    name: cleaned,
    avatarUrl: `https://mc-heads.net/avatar/${encodeURIComponent(cleaned)}/128`,
    verified: false,
    totalProducts: 1,
  };
}
